/**
 * The Box's tool list (v1.16 ticket 07, ob-m73k). The deploy runs this before the build: it builds infra/computer for linux/amd64
 * (the platform Alchemy deploys), reads /etc/box-manifest.json from the built image, and writes
 * apps/worker/src/docs/box-tools.generated.ts, which docs/box.md includes. Run it alone with `node infra/box-tools.ts`.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as Schema from 'effect/Schema'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CONTEXT = join(ROOT, 'infra/computer')
const IMAGE = 'mr-robot-box-manifest:local'
const GENERATED = join(ROOT, 'apps/worker/src/docs/box-tools.generated.ts')

/** The manifest box-manifest.sh writes: the boundary parse of the file read from the image. */
const Tool = Schema.Union([
  Schema.Struct({ kind: Schema.Literal('program'), name: Schema.String, command: Schema.String, version: Schema.String }),
  Schema.Struct({ kind: Schema.Literal('package'), name: Schema.String, version: Schema.String }),
])
const Manifest = Schema.Struct({ manifest: Schema.Literal(1), tools: Schema.Array(Tool) })
type Tool = Schema.Schema.Type<typeof Tool>

/** A single-quoted TypeScript string literal for a value from the manifest. */
const literal = (value: string): string => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const toolLine = (tool: Tool): string => tool.kind === 'program'
  ? `  { kind: 'program', name: ${literal(tool.name)}, command: ${literal(tool.command)}, version: ${literal(tool.version)} },`
  : `  { kind: 'package', name: ${literal(tool.name)}, version: ${literal(tool.version)} },`

const render = (tools: readonly Tool[]): string => [
  '// Generated by infra/box-tools.ts from the Box image\'s /etc/box-manifest.json (v1.16 ticket 07, ob-m73k). Do not edit: run `node infra/box-tools.ts`.',
  '',
  'export type BoxTool =',
  "  | { readonly kind: 'program'; readonly name: string; readonly command: string; readonly version: string }",
  "  | { readonly kind: 'package'; readonly name: string; readonly version: string }",
  '',
  'export const BOX_TOOLS: readonly BoxTool[] = [',
  ...tools.map(toolLine),
  ']',
  '',
].join('\n')

const main = (): void => {
  execFileSync('docker', ['build', '--platform', 'linux/amd64', '-t', IMAGE, CONTEXT], { stdio: ['ignore', 'inherit', 'inherit'] })
  const raw = execFileSync('docker', ['run', '--rm', '--platform', 'linux/amd64', '--entrypoint', 'cat', IMAGE, '/etc/box-manifest.json'], {
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
  })
  const manifest = Schema.decodeUnknownSync(Manifest)(JSON.parse(raw))
  writeFileSync(GENERATED, render(manifest.tools))
  console.log(`box-tools: ${manifest.tools.length} tools from ${IMAGE} written to ${relative(ROOT, GENERATED)}`)
}

try {
  main()
} catch (error) {
  console.error(`box-tools: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
}
